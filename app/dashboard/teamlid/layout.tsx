export default async function TeamlidLayout({ children }: { children: React.ReactNode }) {
  const supabase = await createClient()
  const { data: { user } } = await supabase.auth.getUser()

  if (!user) redirect('/auth/login')

  const { data: profile } = await supabase
    .from('profiles')
    .select('role, full_name')
    .eq('id', user.id)
    .single()

  if (!profile || profile.role !== 'teamlid') redirect('/')

  return (
    <div className="min-h-screen bg-background flex">
      <Sidebar navItems={navItems} role="teamlid" userName={profile.full_name ?? user.email ?? 'Teamlid'} />
      <main className="flex-1 ml-56 min-h-screen overflow-y-auto">
        {children}
      </main>
    </div>
  )
}
